async function main() {
  for (const [mes, ganNoImponibleAcum, deduccionConyugeAcum, deduccionHijoAcum, deduccionHijoIncapAcum, deduccionEspecialAcum] of DEDUCCIONES) {
    const existente = await prisma.tablaGananciasMensual.findUnique({ where: { anio_mes: { anio: ANIO, mes } } });
    if (existente) {
      console.log(`Mes ${mes}/${ANIO} ya estaba cargado — se salta (borralo primero desde /ganancias si necesitás recargarlo).`);
      continue;
    }

    const tabla = await prisma.tablaGananciasMensual.create({
      data: {
        anio: ANIO, mes,
        ganNoImponibleAcum, deduccionEspecialAcum, deduccionConyugeAcum, deduccionHijoAcum, deduccionHijoIncapAcum,
        fuente: FUENTE_DEDUCCIONES,
      },
    });

    const tramos = TRAMOS_POR_MES[mes];
    for (const [desde, hasta, montoFijo, alicuota, sobreExcedenteDe] of tramos) {
      await prisma.tramoGananciasMensual.create({
        data: { tablaId: tabla.id, desde, hasta, montoFijo, alicuota, sobreExcedenteDe },
      });
    }
    console.log(`✔ Mes ${mes}/${ANIO} cargado — ${tramos.length} tramos.`);
  }

  console.log(`\nListo. Fuente de los tramos: ${FUENTE_TRAMOS}`);
  console.log("Próximo paso: el motor de cálculo que use estas tablas (motor-ganancias.mjs) — todavía no armado.");
}

main()
  .catch((e) => { console.error("Error:", e); process.exit(1); })
  .finally(async () => { await prisma.$disconnect(); });
